"""Backend verification for all 12 algorithms: checkpoint provenance, algorithm-specificity,
bundle fidelity, and instance/trajectory correctness against CLRS's reference implementations."""
import hashlib, json, os, pickle, sys, glob
import numpy as np
APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, APP); os.chdir(APP)
import clrs
from clrs._src import algorithms as A, probing, specs
from config import CKPT_DIR, ALGOS
from model_export import build_instance, export_model

ORIG = '/Users/anindya/CLRS/new run/final results and notebook(v3 versions)/checkpoints_v3/mpnn_12graph_algo_checkpoints'
OTHER = '/Users/anindya/CLRS/checkpoints/mpnn'
REPO = os.path.join(APP, 'checkpoints_v3')
ok_all = True
def report(name, ok, detail=''):
    global ok_all; ok_all &= bool(ok); print(('PASS ' if ok else 'FAIL ') + name + (('  ' + detail) if detail else ''))
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()

print('== 1. provenance ==')
report('config.CKPT_DIR points at a checkpoints_v3 directory', 'checkpoints_v3' in CKPT_DIR, CKPT_DIR)
for a in ALGOS:
    o, r = sha(f'{ORIG}/{a}/best.pkl'), sha(f'{REPO}/{a}/best.pkl')
    other = f'{OTHER}/{a}/best.pkl'
    diff_other = (not os.path.exists(other)) or sha(other) != o
    report(f'{a:30s} repo copy == original checkpoints_v3 (sha256 {o[:12]})', o == r and diff_other,
           '' if diff_other else 'IDENTICAL TO THE OTHER CHECKPOINT SET')

print('\n== 2. each checkpoint is specific to its algorithm ==')
params = {a: pickle.load(open(f'{CKPT_DIR}/{a}/best.pkl', 'rb'))['params'] for a in ALGOS}
enc_dec = {a: sorted({k.split('algo_0_')[1].rsplit('_enc_linear', 1)[0].rsplit('_dec_linear', 1)[0] for k in params[a] if 'algo_0_' in k}) for a in ALGOS}
for a in ALGOS:
    spec_fields = sorted(clrs.SPECS[a].keys())
    report(f'{a:30s} encoder/decoder fields == CLRS spec fields', enc_dec[a] == spec_fields, ','.join(enc_dec[a]))
# which spec does each checkpoint fit? (must be exactly one: its own)
mat = []
for a in ALGOS:
    fits = [b for b in ALGOS if enc_dec[a] == sorted(clrs.SPECS[b].keys())]
    mat.append(fits)
    report(f'{a:30s} parameter set fits only its own algorithm', fits == [a], 'fits: ' + ','.join(fits))
same_proc = [a for a in ALGOS[1:] if all(np.array_equal(params[a][k]['w'], params['bfs'][k]['w']) for k in params[a] if 'processor' in k and 'w' in params[a][k])]
report('processor weights differ between algorithms (separately trained)', not same_proc, 'identical to bfs: ' + ','.join(same_proc))

print('\n== 3. browser weight bundles == checkpoint parameters ==')
for a in ALGOS:
    man = json.load(open(f'models/{a}.json')); blob = np.fromfile(f'models/{a}.bin', dtype='<f4')
    man2, blob2 = export_model(a)
    exact = blob.size == blob2.size and np.array_equal(blob, blob2.astype('<f4')) and man == json.loads(json.dumps(man2))
    # spot-check: the processor's first layer in the bundle equals the checkpoint array
    m1 = man['proc']['m1']; w = blob[m1['w']:m1['w'] + m1['din'] * m1['dout']].reshape(m1['din'], m1['dout'])
    ck = params[a]['net/mpnn_aggr_clrs_processor/linear']['w']
    report(f'{a:30s} bundle regenerated from checkpoint is identical; m1 == ckpt', exact and np.array_equal(w, ck), f'{blob.size} floats, algo tag "{man["algo"]}"')

print('\n== 4. instances follow the algorithm (CLRS reference implementation recomputed) ==')
REF = {'bfs': A.bfs, 'dfs': A.dfs, 'bellman_ford': A.bellman_ford, 'dijkstra': A.dijkstra, 'dag_shortest_paths': A.dag_shortest_paths,
       'mst_prim': A.mst_prim, 'mst_kruskal': A.mst_kruskal, 'topological_sort': A.topological_sort,
       'articulation_points': A.articulation_points, 'bridges': A.bridges, 'strongly_connected_components': A.strongly_connected_components,
       'floyd_warshall': A.floyd_warshall}
META = {a: json.load(open(f'algos/{a}/meta.json')) for a in ALGOS}
for a in ALGOS:
    checks = []
    for seed in (1, 7, 42):
        inst, fb = build_instance(a, 12, 0.4, seed, META[a])
        spec = clrs.SPECS[a]
        # fields in the instance are exactly this algorithm's inputs / hints
        ins_ok = sorted(inst['inputs']) == sorted(k for k, v in spec.items() if v[0] == 'input')
        hint_ok = sorted(inst['hints0']) == sorted(k for k, v in spec.items() if v[0] == 'hint')
        # rerun the reference algorithm on the instance's own inputs
        Am = np.asarray(inst['inputs']['A'])
        args = [Am] + ([int(np.argmax(inst['inputs']['s']))] if 's' in inst['inputs'] else [])
        _, probes = REF[a](*args)
        hints_ref = {p: np.asarray(probes[specs.Stage.HINT][loc][p]['data']) for loc in probes[specs.Stage.HINT] for p in probes[specs.Stage.HINT][loc]}
        tgt = META[a]['target']
        ref_tgt = hints_ref[tgt]                                   # (T, N[, C]) as generated by the reference implementation
        if META[a]['target_type'] == 'categorical': ref_tgt = ref_tgt.argmax(-1)
        L = inst['length']
        traj_ok = ref_tgt.shape[0] == L and np.allclose(np.asarray(inst['target_true']), ref_tgt[:L])
        # every hint at step 0 identical too
        h0_ok = all(np.allclose(np.asarray(inst['hints0'][k]), hints_ref[k][0]) for k in inst['hints0'])
        checks.append((ins_ok, hint_ok, traj_ok, h0_ok, L))
    report(f'{a:30s} fields match spec; target trajectory & step-0 hints == CLRS reference on 3 graphs', all(all(c[:4]) for c in checks),
           'lengths ' + '/'.join(str(c[4]) for c in checks))
print('\nOVERALL:', 'ALL PASS' if ok_all else 'FAILURES PRESENT')
